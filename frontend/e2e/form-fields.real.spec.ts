import { test, expect } from '@playwright/test';

test('real JWT/SQL scoring save + reload and system audit filtering', async ({ page }, info) => {
  if (process.env.FORM_FIELDS_REAL_SERVICE !== '1') throw new Error('Run scripts/qualification/run-form-fields-ui.sh in disposable MySQL');
  const login = await page.request.post('/api/auth/login', { data: { username: 'admin', password: process.env.QUALIFICATION_ADMIN_PASSWORD } });
  expect(login.status()).toBe(200);
  const session = await login.json();
  const response = await page.request.get('/api/auth/permissions', { headers: { Authorization: `Bearer ${session.token}` } });
  expect(response.status()).toBe(200);
  await page.addInitScript(({ session, permissions }) => {
    localStorage.setItem('token', session.token); localStorage.setItem('refreshToken', session.refreshToken);
    localStorage.setItem('user', JSON.stringify(session.user)); localStorage.setItem('permissions', JSON.stringify(permissions));
    localStorage.setItem('slide.i18n.locale', 'zh-CN');
  }, { session, permissions: await response.json() });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/settings/monitoring/analysis?view=scoring');
  const scoring = page.locator('scoring-settings-page');
  const available = scoring.getByRole('slider', { name: '可用性', exact: true });
  const performance = scoring.getByRole('slider', { name: '性能', exact: true });
  await expect(available).toBeVisible();
  const originalAvailability = Number(await available.inputValue());
  const originalPerformance = Number(await performance.inputValue());
  const key = originalAvailability < .95 && originalPerformance >= .05 ? 'ArrowRight' : 'ArrowLeft';
  const delta = key === 'ArrowRight' ? .05 : -.05;
  await scoring.locator('label').filter({ hasText: '可用性' }).click(); await expect(available).toBeFocused();
  await page.keyboard.press(key);
  await available.press('Tab'); await expect(performance).toBeFocused();
  await page.keyboard.press(key === 'ArrowRight' ? 'ArrowLeft' : 'ArrowRight');
  const save = page.waitForResponse(r => r.url().includes('/api/scoring/config') && r.request().method() === 'PUT');
  await scoring.getByRole('button', { name: '保存配置' }).click();
  expect((await save).status()).toBe(200);
  await expect(scoring.getByText('权重配置已保存')).toBeVisible();
  await page.reload();
  await expect(available).toHaveValue(String(Number((originalAvailability + delta).toFixed(2))));
  await expect(performance).toHaveValue(String(Number((originalPerformance - delta).toFixed(2))));
  await page.screenshot({ path: info.outputPath('scoring-real-save-reload.png'), fullPage: true });
  const cdp = await page.context().newCDPSession(page);
  const tree = await cdp.send('Accessibility.getFullAXTree');
  for (const name of ['可用性', '性能', '容量', '安全性']) expect(tree.nodes.some(node => node.role?.value === 'slider' && node.name?.value === name)).toBe(true);
  await info.attach('scoring-real-accessibility-tree.json', { body: JSON.stringify(tree, null, 2), contentType: 'application/json' });

  const auditRead = page.waitForResponse(r => r.url().includes('/api/audit/logs?'));
  await page.goto('/audit?view=system'); expect((await auditRead).status()).toBe(200);
  const audit = page.locator('system-audit-page');
  const keyword = audit.getByRole('searchbox', { name: '关键字', exact: true });
  await audit.locator('label.form-label').filter({ hasText: '关键字' }).click(); await expect(keyword).toBeFocused();
  await page.keyboard.press('Tab'); await expect(audit.getByRole('combobox', { name: '操作类型', exact: true })).toBeFocused();
  const auditTree = await cdp.send('Accessibility.getFullAXTree');
  expect(auditTree.nodes.some(node => node.role?.value === 'searchbox' && node.name?.value === '关键字')).toBe(true);
  await info.attach('audit-real-accessibility-tree.json', { body: JSON.stringify(auditTree, null, 2), contentType: 'application/json' });
  await expect(audit.locator('tbody tr').first()).toBeVisible();
  await page.screenshot({ path: info.outputPath('audit-real-data.png'), fullPage: true });
  await keyword.fill('MAX167-no-such-audit-record');
  const empty = page.waitForResponse(r => r.url().includes('/api/audit/logs?') && r.url().includes('MAX167-no-such-audit-record'));
  await audit.getByRole('button', { name: '查询', exact: true }).click();
  expect((await empty).status()).toBe(200);
  await expect(audit.locator('tbody tr')).toHaveCount(0);
  await expect(keyword).toHaveAccessibleName('关键字');
  await page.screenshot({ path: info.outputPath('audit-real-empty.png'), fullPage: true });
  expect(errors).toEqual([]);
});
