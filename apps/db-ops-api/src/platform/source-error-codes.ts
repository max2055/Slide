// Only these identifiers may leave the source API or enter source error logs.
export const sourceErrorCodes = new Set([
  'SOURCE_ADMIN_REQUIRED', 'SOURCE_READ_FORBIDDEN', 'SOURCE_MODEL_EGRESS_DENIED',
  'SOURCE_BINARY_FILE', 'SOURCE_COMMIT_MISMATCH', 'SOURCE_CONFIG_CHANGED', 'SOURCE_CONFIG_INVALID',
  'SOURCE_CONTENT_INVALID', 'SOURCE_CREDENTIAL_ENCRYPTION_UNAVAILABLE', 'SOURCE_CREDENTIAL_INVALID',
  'SOURCE_CREDENTIAL_EXPIRED', 'SOURCE_DUPLICATE_PATH', 'SOURCE_FILE_COUNT_INVALID', 'SOURCE_FILE_TOO_LARGE',
  'SOURCE_IDENTITY_INVALID', 'SOURCE_NOT_CONFIGURED', 'SOURCE_NOT_SYNCED', 'SOURCE_ORIGIN_DENIED',
  'SOURCE_PATH_INVALID', 'SOURCE_PATH_NOT_ALLOWED', 'SOURCE_QUERY_INVALID', 'SOURCE_RATE_LIMITED',
  'SOURCE_READ_BUSY', 'SOURCE_READ_FAILED', 'SOURCE_REF_INVALID', 'SOURCE_REF_NOT_FOUND',
  'SOURCE_REGION_INVALID', 'SOURCE_REGION_TOO_LARGE', 'SOURCE_RELEASE_INVALID', 'SOURCE_REPOSITORY_PATH_REQUIRED',
  'SOURCE_REPOSITORY_NOT_FOUND', 'SOURCE_SAVED_CREDENTIAL_UNAVAILABLE', 'SOURCE_SIGNING_KEY_INVALID',
  'SOURCE_SNAPSHOT_POLICY_CHANGED', 'SOURCE_SNAPSHOT_TOO_LARGE', 'SOURCE_SNAPSHOT_UNTRUSTED',
  'SOURCE_STORAGE_UNAVAILABLE', 'SOURCE_SYMBOL_INVALID', 'SOURCE_SYNC_BUSY', 'SOURCE_SYNC_DEADLINE',
  'SOURCE_SYNC_FAILED', 'SOURCE_UNAVAILABLE', 'SOURCE_UPSTREAM_UNAVAILABLE', 'SOURCE_UPSTREAM_FORBIDDEN',
  'SOURCE_UPSTREAM_PERMISSION_DENIED', 'SOURCE_UPSTREAM_RATE_LIMITED',
]);
export function safeSourceErrorCode(error: unknown, fallback = 'SOURCE_UNAVAILABLE') {
  if (error instanceof Error && sourceErrorCodes.has(error.message)) return error.message;
  if (error instanceof Error && 'code' in error && ['EACCES', 'ENOSPC', 'EROFS', 'EIO'].includes(String(error.code))) return 'SOURCE_STORAGE_UNAVAILABLE';
  return fallback;
}
